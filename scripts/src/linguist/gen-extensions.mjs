#!/usr/bin/env node
// Generates the table of file extensions GitHub Linguist knows, which `anchr coverage` uses to
// decide whether `name.ext` in prose is file-shaped:
// @noref[scripts/src/linguist/gen-extensions.mjs, languages.yml]
//
//   @ref[crates/anchr-core/src/coverage/linguist/linguist.rs]   sorted `&[&str]`, one entry per line
//
// The source is pinned to one Linguist commit so regeneration is deterministic; CI regenerates
// from the pin and fails on any diff. Bumping Linguist is a change to LINGUIST_REF plus a rerun,
// reviewed as one commit.
//
//   node scripts/src/linguist/gen-extensions.mjs [--ref <sha>] [--from <languages.yml>] \
//        [--out <path>] [--check]

import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

import { repoRoot } from "../repo-root.mjs";

const LINGUIST_REF = "e0c78d62c42abae6122235d8e68a7aa43eef89da";
const LINGUIST_TAG = "v9.7.0";
const SOURCE_PATH = "lib/linguist/languages.yml";
const MINIMUM_ENTRIES = 1000;

const REPO_ROOT = repoRoot(import.meta.url);
const DEFAULT_OUT = join(REPO_ROOT, "crates", "anchr-core", "src", "coverage", "linguist", "linguist.rs");

async function main() {
  const { values: args } = parseArgs({
    options: {
      ref: { type: "string", default: LINGUIST_REF },
      from: { type: "string" },
      out: { type: "string", default: DEFAULT_OUT },
      check: { type: "boolean", default: false },
    },
  });

  const yaml = args.from ? readFileSync(args.from, "utf8") : await fetchLanguagesYaml(args.ref);
  const rendered = render(extractExtensions(yaml), args.ref);

  if (args.check) {
    const current = readFileSync(args.out, "utf8");
    if (current !== rendered) {
      console.error(`${args.out} is stale; rerun without --check to regenerate`);
      process.exit(1);
    }
    console.log(`${args.out} is up to date`);
  } else {
    writeFileSync(args.out, rendered);
    console.log(`wrote ${args.out}`);
  }
}

// Only the CLI invocation runs; importing the module for tests must not fetch or write.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}

export { extractExtensions, render, LINGUIST_TAG, MINIMUM_ENTRIES };

async function fetchLanguagesYaml(ref) {
  const url = `https://raw.githubusercontent.com/github-linguist/linguist/${ref}/${SOURCE_PATH}`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`fetching ${url}: ${response.status} ${response.statusText}`);
  }
  return response.text();
}

// languages.yml is regular enough that a line-state parser beats a YAML dependency: every
// language is a top-level key whose `extensions:` list is two-space indented, one dotted entry
// per line. Sibling lists (`filenames:`, `interpreters:`, `aliases:`) share the item shape and
// must not be read, so list mode ends at the first line that is not an item.
// `minimum` is a parameter so the guard itself is testable; production always uses the default,
// which is high enough that a layout change shows up as an error rather than a thinned table.
function extractExtensions(yaml, minimum = MINIMUM_ENTRIES) {
  const kept = new Set();
  const dropped = { multiDot: 0, nonAscii: 0, allDigit: 0 };
  let inExtensions = false;
  for (const line of yaml.split("\n")) {
    if (/^  extensions:\s*$/.test(line)) {
      inExtensions = true;
      continue;
    }
    const item = inExtensions ? line.match(/^  - "?(\.[^"\s]+)"?\s*$/) : null;
    if (!item) {
      inExtensions = false;
      continue;
    }
    const extension = item[1].slice(1).toLowerCase();
    if (extension.includes(".")) {
      dropped.multiDot += 1;
    } else if (!/^[a-z0-9_+-]+$/.test(extension)) {
      dropped.nonAscii += 1;
    } else if (/^\d+$/.test(extension)) {
      dropped.allDigit += 1;
    } else {
      kept.add(extension);
    }
  }
  if (kept.size < minimum) {
    throw new Error(`only ${kept.size} extensions parsed; the languages.yml layout has changed`);
  }
  // Byte order, to match Rust's `str` ordering for `binary_search`. ASCII only, so code units
  // and bytes agree.
  const sorted = [...kept].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  return { sorted, dropped };
}

function render({ sorted, dropped }, ref) {
  const lines = [
    "//! File extensions GitHub Linguist knows, lowercased, leading dot stripped.",
    "//!",
    "//! Generated by @ref[scripts/src/linguist/gen-extensions.mjs]; do not edit by hand.",
    `//! Source (${LINGUIST_TAG}): https://github.com/github-linguist/linguist/blob/${ref}/${SOURCE_PATH}`,
    `//! ${sorted.length} entries; dropped ${dropped.multiDot} multi-dot, ${dropped.nonAscii} non-ASCII, ${dropped.allDigit} all-digit.`,
    "",
    "pub(crate) fn is_linguist_extension(extension: &str) -> bool {",
    "    LINGUIST_EXTENSIONS.binary_search(&extension).is_ok()",
    "}",
    "",
    "#[rustfmt::skip]",
    "pub(crate) static LINGUIST_EXTENSIONS: &[&str] = &[",
    ...sorted.map((extension) => `    "${extension}",`),
    "];",
    "",
    // Last, so the table above it is not an item after a test module.
    "#[cfg(test)]",
    "mod linguist_tests;",
    "",
  ];
  return lines.join("\n");
}
