// @noref[scripts/src/docs/gen-index.mjs, docs/README.md, a.md, b.md, z.md, sub/x.md, design/aliases.md]
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";

import { collectDocs, groupDocs, parseFrontmatter, render } from "../../src/docs/gen-index.mjs";

const DOC = `---
title: Testing
description: How tests are laid out. Read before adding a test.
tags: [tests, ci]
---

# Testing
`;

test("frontmatter yields title, description and tags", () => {
  assert.deepEqual(parseFrontmatter(DOC, "a.md"), {
    title: "Testing",
    description: "How tests are laid out. Read before adding a test.",
    tags: ["tests", "ci"],
  });
});

test("tags are optional and CRLF line endings are accepted", () => {
  const parsed = parseFrontmatter("---\r\ntitle: T\r\ndescription: D\r\n---\r\n", "a.md");
  assert.deepEqual(parsed.tags, []);
});

// A document the index cannot describe must fail loudly, or it silently vanishes from the index.
test("a document without frontmatter, or with an unclosed or incomplete block, is an error naming it", () => {
  assert.throws(() => parseFrontmatter("# No frontmatter\n", "a.md"), /a\.md: missing frontmatter/);
  assert.throws(() => parseFrontmatter("---\ntitle: T\n", "b.md"), /b\.md: frontmatter is not closed/);
  assert.throws(() => parseFrontmatter("---\ntitle: T\n---\n", "z.md"), /z\.md: frontmatter is missing `description`/);
  assert.throws(() => parseFrontmatter("---\ntitle: T\ndescription: D\ntags: tests\n---\n", "a.md"), /tags must be a bracketed list/);
  assert.throws(() => parseFrontmatter("---\nnot a field\n---\n", "a.md"), /not `key: value`/);
});

test("the top-level directory comes first, then subdirectories by name, files by path", () => {
  const docs = [
    { path: "sub/x.md", title: "X", description: "d", tags: [] },
    { path: "z.md", title: "Z", description: "d", tags: [] },
    { path: "design/aliases.md", title: "Aliases", description: "d", tags: [] },
    { path: "a.md", title: "A", description: "d", tags: [] },
  ];
  const groups = groupDocs(docs);
  assert.deepEqual(
    groups.map((g) => [g.directory, g.heading, g.docs.map((d) => d.path)]),
    [
      ["", "Core", ["a.md", "z.md"]],
      ["design", "Feature designs", ["design/aliases.md"]],
      ["sub", "sub", ["sub/x.md"]],
    ],
  );
});

test("the rendered index names its generator, links each doc, and escapes pipes", () => {
  const output = render([
    { path: "a.md", title: "A", description: "one | two", tags: ["x", "y"] },
    { path: "design/b.md", title: "B", description: "d", tags: [] },
  ]);
  assert.match(output, /Generated by @ref\[scripts\/src\/docs\/gen-index\.mjs\]/);
  assert.match(output, /\| \[A\]\(a\.md\) \| one \\\| two \| x, y \|/);
  assert.match(output, /## Feature designs\n\n\| Doc \| Description \| Tags \|\n\|---\|---\|---\|\n\| \[B\]\(design\/b\.md\) \| d \|  \|/);
  assert.ok(output.endsWith("\n"));
});

test("collecting a directory reads every markdown file except the index and keeps forward slashes", () => {
  const docs = mkdtempSync(join(tmpdir(), "gen-index-"));
  mkdirSync(join(docs, "design"));
  writeFileSync(join(docs, "README.md"), "# stale index, ignored\n");
  writeFileSync(join(docs, "z.md"), DOC);
  writeFileSync(join(docs, "design", "aliases.md"), "---\ntitle: Aliases\ndescription: D\n---\n");
  writeFileSync(join(docs, "notes.txt"), "not markdown");
  assert.deepEqual(
    collectDocs(docs).map((d) => d.path),
    ["design/aliases.md", "z.md"],
  );
});
